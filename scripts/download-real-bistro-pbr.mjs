import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Poly Haven publishes these CC0 materials with diffuse, ARM, normal and
// displacement maps. The runtime only needs 1K output for the desktop window;
// 4K sources are fetched and resized locally to keep the runtime preload bounded
// while preserving enough texel density for the near wall and paving.
const root = path.resolve('public/assets/orca/bistro/real-pbr');
const sourceRoot = 'https://dl.polyhaven.org/file/ph-assets/Textures/jpg/4k';
const sets = {
  wall: { name: 'plastered_stone_wall', files: ['diff', 'arm', 'nor_gl', 'disp'] },
  ground: { name: 'cobblestone_floor_001', files: ['diff', 'arm', 'nor_gl', 'disp'] },
};

async function download(url) {
  const response = await fetch(url, { headers: { 'user-agent': 'OutOfWindow-Demo' } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText} for ${url}`);
  return Buffer.from(await response.arrayBuffer());
}

await fs.mkdir(root, { recursive: true });
for (const [kind, set] of Object.entries(sets)) {
  const destination = path.join(root, kind);
  await fs.mkdir(destination, { recursive: true });
  for (const channel of set.files) {
    const url = `${sourceRoot}/${set.name}/${set.name}_${channel}_4k.jpg`;
    const output = path.join(destination, `${channel}.jpg`);
    const source = await download(url);
    await sharp(source).resize({ width: 1024, height: 1024, fit: 'cover' }).jpeg({ quality: 92, chromaSubsampling: '4:4:4' }).toFile(output);
    console.log(`${kind}/${channel}.jpg`);
  }
}
await fs.writeFile(path.join(root, 'LICENSE.txt'), 'Poly Haven materials: CC0\nSources: plastered_stone_wall, cobblestone_floor_001\n');
const config = `// Generated by scripts/download-real-bistro-pbr.mjs\nexport const BISTRO_REAL_PBR = { enabled: true, wall: './assets/orca/bistro/real-pbr/wall', ground: './assets/orca/bistro/real-pbr/ground' };\n`;
await fs.writeFile(path.resolve('src/bistro-pbr-config.js'), config);
console.log('Real Bistro PBR channels installed and runtime flag enabled.');
